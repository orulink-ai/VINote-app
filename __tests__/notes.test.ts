import { createNote, getNote, renameNote, deleteNote, listNotes, listLocalNotes, shareNoteFile, editNoteContent, noteRevisions, saveSourceNote } from '../src/lib/notes'
import { readAccountId } from '../src/lib/storage'
import FS from 'react-native-fs'
import Share from 'react-native-share'
jest.mock('../src/lib/storage', () => ({ readAccountId: jest.fn() }))
jest.mock('../src/lib/workspace', () => ({ requestWorkspaceSync: jest.fn() }))

test('an editor based on an older revision cannot replace newly received content', async () => {
  jest.mocked(readAccountId).mockResolvedValue('concurrent-editor')
  const note = await createNote({ title: '并发编辑检查', content: '# 打开时正文', task_id: 'concurrent-edit' }, 'concurrent-editor')
  await editNoteContent(note.id, '# 另一端的新正文')
  await expect(editNoteContent(note.id, '# 尚未提交的草稿', note)).rejects.toThrow('正文已有新修订')
  expect((await getNote(note.id)).content).toBe('# 另一端的新正文')
  await deleteNote(note.id)
})

test('edits preserve prior content without polluting the note library or generation versions', async () => {
  jest.mocked(readAccountId).mockResolvedValue('editor')
  const note = await createNote({ title: '会议', content: '# 原始内容', task_id: 'editable' }, 'editor')
  await editNoteContent(note.id, '# 修改内容')
  expect((await getNote(note.id)).version).toBe(1)
  expect((await noteRevisions(note.id))[0].content).toBe('# 原始内容')
  expect(await listNotes()).toHaveLength(1)
  jest.mocked(readAccountId).mockResolvedValue('another')
  expect(await noteRevisions(note.id)).toEqual([])
  jest.mocked(readAccountId).mockResolvedValue('editor')
  await deleteNote(note.id)
  expect((await noteRevisions(note.id))[0].content).toBe('# 原始内容')
  expect((await getNote(note.id)).deleted).toBe(true)
  expect(await listNotes()).toEqual([])
})
test('local minutes are isolated by account and support rename and delete', async () => {
  jest.mocked(readAccountId).mockResolvedValue('alice')
  const note = await createNote({ title: '会议', content: '# 决议', task_id: 'r1' }, 'alice')
  expect((await renameNote(note.id, '新名称')).title).toBe('新名称')
  jest.mocked(readAccountId).mockResolvedValue('bob')
  expect(await listNotes()).toEqual([])
  await expect(getNote(note.id)).rejects.toMatchObject({ status: 404 })
  await expect(createNote({ title: '会议', content: '私密', task_id: 'r2' }, 'alice')).rejects.toThrow('账号已切换')
  jest.mocked(readAccountId).mockResolvedValue('alice')
  await deleteNote(note.id)
  expect((await getNote(note.id)).deleted).toBe(true)
  expect(await listNotes()).toEqual([])
})
test('same recording lists its latest version while all numbered originals remain readable', async () => {
  jest.mocked(readAccountId).mockResolvedValue('alice')
  const first = await createNote({ title: '同一段录音', content: '# 第一版', task_id: 'record-version' }, 'alice')
  const second = await createNote({ title: '同一段录音', content: '# 第二版', task_id: 'record-version' }, 'alice')
  expect(first).toMatchObject({ id: 'app-record-version', version: 1 })
  expect(second).toMatchObject({ id: 'app-record-version-v2', version: 2 })
  expect((await listNotes()).filter(note => note.task_id === 'record-version')).toEqual([second])
  expect((await listLocalNotes()).filter(note => note.task_id === 'record-version')).toHaveLength(2)
  expect((await getNote(first.id)).content).toBe('# 第一版')
})
test('creating an occupied version never overwrites the previous note', async () => {
  jest.mocked(readAccountId).mockResolvedValue('alice')
  const first = await createNote({ title: '录音', content: '# 原纪要', task_id: 'collision' }, 'alice', 1)
  await expect(createNote({ title: '录音', content: '# 新纪要', task_id: 'collision' }, 'alice', 1)).rejects.toThrow('已存在')
  expect((await getNote(first.id)).content).toBe('# 原纪要')
})
test('shares the selected version as a Markdown file kept available for the receiving app', async () => {
  jest.mocked(readAccountId).mockResolvedValue('alice')
  const note = await createNote({ title: '客户/会议', content: '# 第二版\n行动项', task_id: 'share-version' }, 'alice', 2)
  await shareNoteFile(note)
  expect(FS.writeFile).toHaveBeenCalledWith(expect.stringMatching(/客户_会议_v2\.md$/), note.content, 'utf8')
  expect(Share.open).toHaveBeenCalledWith(expect.objectContaining({ url: expect.stringMatching(/客户_会议_v2\.md$/), type: 'text/markdown' }))
  expect(FS.unlink).not.toHaveBeenCalled()
})

test('source summaries use a workspace-compatible type and never impersonate a local recording', async () => {
  jest.mocked(readAccountId).mockResolvedValue('source-owner')
  const note = await saveSourceNote('source-task', '文字总结', '# 总结', 'transcript', 'source-owner')
  expect(note.source_type).toBe('file')
  expect(note.task_id).toBeUndefined()
  expect(await saveSourceNote('source-task', '重复返回', '# 不应替换', 'transcript', 'source-owner')).toEqual(note)
  expect((await listLocalNotes()).filter(row => row.id === note.id)).toHaveLength(1)
})
