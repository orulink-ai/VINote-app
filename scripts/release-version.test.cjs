const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')

test('0.1.4 package, Android and iOS versions agree without downgrading Android code', () => {
  const pkg = JSON.parse(read('package.json'))
  const lock = JSON.parse(read('package-lock.json'))
  assert.equal(pkg.version, '0.1.4')
  assert.equal(lock.version, pkg.version)
  assert.equal(lock.packages[''].version, pkg.version)
  const android = read('android/app/build.gradle')
  assert.match(android, /versionName "0\.1\.4"/)
  assert.match(android, /versionCode 9\b/)
  assert.doesNotMatch(read('android/app/src/main/AndroidManifest.xml'), /android:version(?:Name|Code)/)
  const ios = read('ios/VINoteApp.xcodeproj/project.pbxproj')
  assert.deepEqual([...ios.matchAll(/MARKETING_VERSION = ([^;]+);/g)].map(m => m[1]), ['0.1.4', '0.1.4'])
  assert.deepEqual([...ios.matchAll(/CURRENT_PROJECT_VERSION = ([^;]+);/g)].map(m => m[1]), ['5', '5'])
  const plist = read('ios/VINoteApp/Info.plist')
  assert.ok(plist.includes('$(MARKETING_VERSION)'))
  assert.ok(plist.includes('$(CURRENT_PROJECT_VERSION)'))
})
